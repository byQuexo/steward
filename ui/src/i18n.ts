export const messages = { de: de as Messages, en } as const;
export type Locale = keyof typeof messages;

/** `de`, `de-DE`, `de_AT` → `de`; anything unknown → `en`. */
export function pickLocale(locale: string | undefined | null): Locale {
  const l = (locale ?? '').toLowerCase().slice(0, 2);
  return l === 'de' ? 'de' : 'en';
}

export type Vars = Record<string, string | number>;

export function translate(locale: Locale, key: MessageKey, vars?: Vars): string {
  const s = messages[locale][key] ?? messages.en[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export type T = (key: MessageKey, vars?: Vars) => string;

export function makeT(locale: Locale): T {
  return (key, vars) => translate(locale, key, vars);
}

/** BCP 47 tag for Intl formatting. */
export function intlLocale(locale: Locale): string {
  return locale === 'de' ? 'de-DE' : 'en-GB';
}
