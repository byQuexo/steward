"""steward-seed: write (or check) a profile's data/ directory from its seed/ sources.

    uv run steward-seed --profile ../profiles/acme           # write data/
    uv run steward-seed --profile ../profiles/acme --check   # fail if data/ differs
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

from . import canonical, docs, keycloak, records


def dump(obj: Any) -> bytes:
    return (json.dumps(obj, ensure_ascii=False, indent=2, sort_keys=False) + "\n").encode("utf-8")


def generate(profile: Path) -> dict[str, bytes]:
    cfg = yaml.safe_load((profile / "seed" / "seed.yaml").read_text(encoding="utf-8"))
    acl = (yaml.safe_load((profile / "docs_acl.yaml").read_text(encoding="utf-8")) or {}).get("teams", {})
    policy_path = profile / "warden" / "policy.yaml"
    roles = sorted((yaml.safe_load(policy_path.read_text(encoding="utf-8")) or {}).get("roles", {})) if policy_path.exists() else []
    seed, locale = int(cfg["seed"]), cfg.get("locale", "en_US")

    corpus, files = docs.build(profile / "seed" / "docs", seed, locale)
    doc_ids = [d["doc_id"] for d in corpus]
    users = records.users(cfg, acl, doc_ids)
    out: dict[str, bytes] = dict(files)
    out["users.json"] = dump(users)
    out["corpus.json"] = dump(corpus)
    if "hr" in cfg:
        out["hr.json"] = dump(records.hr(cfg, users, seed, locale))
    if "crm" in cfg:
        out["crm.json"] = dump(records.crm(cfg, seed, locale))
    if "tickets" in cfg:
        out["tickets.json"] = dump(records.tickets(cfg, users, seed, locale))
    if "jira" in cfg:
        out["jira.json"] = dump(records.jira(cfg, seed, locale))
    if "chat" in cfg:
        out["chat.json"] = dump(records.chat(cfg, users, seed, locale))
    if "github" in cfg:
        out["github.json"] = dump(records.github(cfg, seed, locale))
    if roles:
        out["keycloak/realm.json"] = dump(keycloak.realm(cfg, users, roles))
    out["REPORT.md"] = report(cfg, out, corpus, users)
    return out


def report(cfg: dict[str, Any], files: dict[str, bytes], corpus: list[dict[str, Any]], users: list[dict[str, Any]]) -> bytes:
    lines = [
        f"# Seed report: {cfg.get('company', '')}",
        "",
        f"Generated by `steward-seed` from `seed/seed.yaml` (seed {cfg['seed']}, locale {cfg.get('locale')}).",
        "All data is synthetic. Regenerating with the same inputs yields identical content on every",
        "OS (pixels for images, decompressed streams for PDFs; compressed bytes depend on the zlib",
        "build); CI checks this with `steward-seed --check`.",
        "",
        f"- {len(users)} demo users, {len(corpus)} documents ({sum(len(d['pages']) for d in corpus)} pages, "
        f"{sum(1 for d in corpus if d['scanned'])} scanned)",
        "",
        "| File | Content SHA-256 |",
        "|---|---|",
    ]
    for name in sorted(files):
        lines.append(f"| `{name}` | `{canonical.digest(name, files[name])[:16]}` |")
    return ("\n".join(lines) + "\n").encode("utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="steward-seed")
    ap.add_argument("--profile", required=True, type=Path)
    ap.add_argument("--check", action="store_true", help="compare with data/ instead of writing")
    args = ap.parse_args(argv)
    profile: Path = args.profile.resolve()
    data = profile / "data"
    out = generate(profile)
    if args.check:
        stale = [
            n
            for n, b in sorted(out.items())
            if not (data / n).exists() or canonical.content(n, (data / n).read_bytes()) != canonical.content(n, b)
        ]
        extra = sorted(str(p.relative_to(data)).replace("\\", "/") for p in data.rglob("*") if p.is_file()) if data.exists() else []
        extra = [e for e in extra if e not in out]
        for n in stale:
            print(f"differs: {n}", file=sys.stderr)
        for n in extra:
            print(f"not generated: {n}", file=sys.stderr)
        if stale or extra:
            print(f"{profile.name}: data/ is out of date; run steward-seed --profile {args.profile}", file=sys.stderr)
            return 1
        print(f"{profile.name}: {len(out)} files up to date")
        return 0
    for name, content in out.items():
        path = data / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    print(f"{profile.name}: wrote {len(out)} files to {data}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
