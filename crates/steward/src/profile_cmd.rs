//! `steward profile generate|check`: derive Warden files from the profile's connectors.

use std::path::Path;

use steward_config::{generate_catalog, ConfigError, Connector};

fn read_connectors(profile: &Path) -> Result<(String, Vec<Connector>, Option<String>), String> {
    let meta: serde_json::Value =
        serde_norway::from_str(&std::fs::read_to_string(profile.join("profile.yaml")).map_err(|e| e.to_string())?)
            .map_err(|e| e.to_string())?;
    let name = meta["name"].as_str().unwrap_or("profile").to_string();
    let mut files: Vec<_> = std::fs::read_dir(profile.join("connectors"))
        .map_err(|e| format!("connectors/: {e}"))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().and_then(|x| x.to_str()) == Some("yaml"))
        .collect();
    files.sort();
    let mut connectors = Vec::new();
    for f in files {
        let c: Connector = serde_norway::from_str(&std::fs::read_to_string(&f).map_err(|e| e.to_string())?)
            .map_err(|e| format!("{}: {e}", f.display()))?;
        connectors.push(c);
    }
    let extra_path = profile.join("warden/catalog.extra.yaml");
    let extra = if extra_path.exists() { Some(std::fs::read_to_string(&extra_path).map_err(|e| e.to_string())?) } else { None };
    Ok((name, connectors, extra))
}

/// Write (or with `check`, compare) `warden/catalog.yaml`, then load the whole profile.
pub fn run(profile: &Path, check: bool) -> Result<i32, String> {
    let (name, connectors, extra) = read_connectors(profile)?;
    let catalog = generate_catalog(&name, &connectors, extra.as_deref())?;
    let path = profile.join("warden/catalog.yaml");
    if check {
        let current = std::fs::read_to_string(&path).unwrap_or_default().replace("\r\n", "\n");
        if current != catalog {
            eprintln!("{}: out of date; run `steward profile generate --profile {}`", path.display(), profile.display());
            return Ok(1);
        }
    } else {
        std::fs::write(&path, &catalog).map_err(|e| format!("{}: {e}", path.display()))?;
        eprintln!("wrote {}", path.display());
    }
    let p = steward_config::Profile::load(profile).map_err(|e: ConfigError| e.to_string())?;
    let engine = p.engine().map_err(|e| e.to_string())?;
    for w in engine.warnings() {
        eprintln!("warning: {w}");
    }
    println!(
        "profile `{}`: {} connectors, {} users, {} demo scenarios, policy {}",
        p.meta.name,
        p.connectors.len(),
        p.users.len(),
        p.scenarios.len(),
        engine.version()
    );
    Ok(0)
}

/// `steward profile deploy`: the compose configuration for a profile (Keycloak realm from the
/// seed, `warden sts`, the Warden gateway with upstreams from the connectors, the assistant).
pub fn deploy(profile_dir: &Path, out: &Path) -> Result<i32, String> {
    let mapping = steward_config::TOKEN_MAPPING;
    let p = steward_config::Profile::load(profile_dir).map_err(|e| e.to_string())?;
    let realm_file = p.data_dir().join("keycloak/realm.json");
    let realm: serde_json::Value = serde_json::from_str(
        &std::fs::read_to_string(&realm_file).map_err(|e| format!("{}: {e} (run the seed first)", realm_file.display()))?,
    )
    .map_err(|e| e.to_string())?;
    let realm_name = realm["realm"].as_str().ok_or("realm.json has no realm")?;
    let client = |r: steward_config::AgentRole| p.agent(r).map(|a| a.client_id.clone()).unwrap_or_default();
    let (bot, research, action) = (
        client(steward_config::AgentRole::Orchestrator),
        client(steward_config::AgentRole::Research),
        client(steward_config::AgentRole::Action),
    );
    let kc_public = format!("http://localhost:8080/realms/{realm_name}");
    let kc_internal = format!("http://keycloak:8080/realms/{realm_name}");
    let audience = "http://localhost:8088/mcp";
    let header =
        format!("# GENERATED by `steward profile deploy --profile profiles/{} --out deploy/{}`. Do not edit.\n", p.meta.name, p.meta.name);
    std::fs::create_dir_all(out).map_err(|e| e.to_string())?;
    let files = [
        (
            "steward.yaml",
            format!(
                "{header}profile: /profile\nlisten: 0.0.0.0:8000\npublic_url: http://localhost:8000\ndata_dir: /data\nui_dir: /app/ui\noidc: {{ issuer: {kc_public}, backchannel: http://keycloak:8080, client_id: {bot}, client_secret_env: OIDC_CLIENT_SECRET }}\nkeycloak: {{ base: http://keycloak:8080, realm: {realm_name}, client_id: steward-console, client_secret_env: KEYCLOAK_CONSOLE_SECRET }}\ngateway: {{ url: http://gateway:8088/mcp, audience: {audience}, admin_url: http://gateway:8089, admin_token_env: WARDEN_ADMIN_TOKEN, audit_dir: /audit }}\nsts: {{ url: http://sts:9400, bot_secret_env: STS_BOT_SECRET, console_secret_env: STS_CONSOLE_SECRET, a2a_proxy_secret_env: STS_A2A_PROXY_SECRET }}\na2a: {{ research: http://a2a-research:9500, action: http://a2a-action:9500 }}\napproval_secret_env: APPROVAL_WEBHOOK_SECRET\notlp_traces: http://phoenix:6006/v1/traces\n"
            ),
        ),
        (
            "sts.yaml",
            format!(
                "{header}# warden sts: delegation (act chains), test-as-user, revocation. Trusts Keycloak for user tokens.\nissuer: http://sts:9400\nkey_file: /var/lib/sts/sts-key.pem\ntrust: trust.yaml\npolicy: /profile/warden/policy.yaml\nlisten: 0.0.0.0:9400\ntoken_ttl_s: 300\nclients:\n  {bot}: {{ secret_env: STS_BOT_SECRET, can_impersonate: true }}\n  {research}: {{ secret_env: STS_BOT_SECRET }}\n  {action}: {{ secret_env: STS_BOT_SECRET }}\n  gateway: {{ secret_env: GATEWAY_STS_SECRET, accept_audiences: [\"{audience}\"], may_exchange_to: [steward-mcp] }}\n  steward-console: {{ secret_env: STS_CONSOLE_SECRET, can_revoke_subjects: true }}\n  a2a-proxy: {{ secret_env: STS_A2A_PROXY_SECRET, accept_audiences: [steward-a2a], may_exchange_to: [steward-agents] }}\n"
            ),
        ),
        (
            "trust.yaml",
            format!(
                "{header}version: 1\nissuers:\n  - issuer: {kc_public}\n    audience: \"{audience}\"\n    jwks_uri: {kc_internal}/protocol/openid-connect/certs\n    algorithms: [RS256]\n    mapping: {mapping}\nscope_claim: ignore\n"
            ),
        ),
        (
            "identity.yaml",
            format!(
                "{header}# The gateway trusts Keycloak (users) and warden sts (delegation, test-as), and asks both by\n# introspection on every call, so revocation and role changes apply immediately.\nversion: 1\nissuers:\n  - issuer: {kc_public}\n    audience: \"{audience}\"\n    jwks_uri: {kc_internal}/protocol/openid-connect/certs\n    algorithms: [RS256]\n    mapping: {mapping}\n    introspection: {{ endpoint: {kc_internal}/protocol/openid-connect/token/introspect, client_id: warden-gateway, secret_env: KEYCLOAK_GATEWAY_SECRET, cache_s: 2 }}\n  - issuer: http://sts:9400\n    audience: \"{audience}\"\n    jwks_uri: http://sts:9400/jwks\n    algorithms: [ES256]\n    mapping: {mapping}\n    introspection: {{ endpoint: http://sts:9400/introspect, client_id: gateway, secret_env: GATEWAY_STS_SECRET, cache_s: 2 }}\ndelegation_issuers: [http://sts:9400]\nscope_claim: ignore\n"
            ),
        ),
        (
            "gateway.yaml",
            format!(
                "{header}listen: 0.0.0.0:8088\nadmin_listen: 0.0.0.0:8089\nadmin_token_env: WARDEN_ADMIN_TOKEN\npublic_url: {audience}\nidentity: identity.yaml\npolicy: {{ catalog: /profile/warden/catalog.yaml, policy: /profile/warden/policy.yaml }}\nhealth: {{ open_after_failures: 3, cooldown_ms: 30000 }}\n{}approval: {{ approver: webhook, url: http://steward:8000/hooks/warden/approval, secret_env: APPROVAL_WEBHOOK_SECRET, timeout_ms: {}, progress_interval_ms: 2000 }}\naudit:\n  sinks:\n    - {{ type: jsonl, dir: /var/lib/warden/audit, chain: gw-1, checkpoint_every: 20 }}\n    - {{ type: stdout }}\n  hmac_key_env: AUDIT_HMAC_KEY\nkill_switch: {{ file: /var/lib/warden/kill }}\n",
                steward_config::generate_gateway_yaml(
                    &p.connectors,
                    &steward_config::GatewayTargets { builtin_base: "http://mcp:8100", token_url: "http://sts:9400/token", upstream_audience: "steward-mcp" }
                ),
                (p.approvals.timeout_s + 5) * 1000
            ),
        ),
    ];
    for (name, content) in files {
        let path = out.join(name);
        std::fs::write(&path, content).map_err(|e| format!("{}: {e}", path.display()))?;
        eprintln!("wrote {}", path.display());
    }
    Ok(0)
}
