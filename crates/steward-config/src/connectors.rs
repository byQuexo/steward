//! Connectors: the systems a company plugs in. Each connector names an MCP server and the
//! tools it exposes, with the scopes Warden requires for each. `warden/catalog.yaml` and the
//! gateway's `upstreams:` are generated from these files, so adding a system is one YAML file.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde::{Deserialize, Serialize};

#[derive(Clone, Debug, Deserialize, Serialize, PartialEq)]
#[serde(rename_all = "snake_case", deny_unknown_fields)]
pub enum ServerSpec {
    /// One of Steward's built-in servers (`steward-mcp`): hr, crm, ticket, docs, jira, chat, github.
    Builtin(String),
    /// Any Streamable HTTP MCP server.
    Url(String),
    /// A local stdio MCP server started by the gateway.
    Command(Vec<String>),
}

#[derive(Clone, Debug, Deserialize, Serialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct ToolSpec {
    pub scopes: Vec<String>,
    #[serde(default = "read")]
    pub sensitivity: String,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tags: Vec<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
}

fn read() -> String {
    "read".into()
}

#[derive(Clone, Debug, Deserialize, Serialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct Connector {
    /// Upstream name; tools appear as `<name>.<tool>`.
    pub name: String,
    pub title: String,
    #[serde(default)]
    pub description: String,
    #[serde(with = "serde_norway::with::singleton_map")]
    pub server: ServerSpec,
    /// Seed file the built-in server serves (relative to the profile).
    #[serde(default)]
    pub data: Option<String>,
    /// Resource URI prefixes this upstream serves (`docs://`).
    #[serde(default)]
    pub resources: Vec<String>,
    /// Environment variables a stdio server may see.
    #[serde(default)]
    pub pass_env: Vec<String>,
    pub tools: BTreeMap<String, ToolSpec>,
}

impl Connector {
    pub(crate) fn validate(&self) -> Result<(), String> {
        let ident = |s: &str| !s.is_empty() && s.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_' || c == '-');
        if !ident(&self.name) {
            return Err(format!("connector name `{}` must be lowercase ASCII", self.name));
        }
        if self.tools.is_empty() {
            return Err("a connector needs at least one tool".into());
        }
        for (t, spec) in &self.tools {
            if !ident(t) {
                return Err(format!("tool name `{t}` must be lowercase ASCII"));
            }
            if spec.scopes.is_empty() {
                return Err(format!("tool `{t}` needs at least one scope (unscoped tools are denied anyway)"));
            }
            if !matches!(spec.sensitivity.as_str(), "read" | "write") {
                return Err(format!("tool `{t}`: sensitivity must be `read` or `write`"));
            }
        }
        if let ServerSpec::Builtin(b) = &self.server {
            if !BUILTINS.contains(&b.as_str()) {
                return Err(format!("unknown built-in server `{b}` (one of {})", BUILTINS.join(", ")));
            }
        }
        Ok(())
    }
}

pub const BUILTINS: &[&str] = &["hr", "crm", "ticket", "docs", "jira", "chat", "github"];

fn list(items: &[String]) -> String {
    items.iter().map(|s| yaml_scalar(s)).collect::<Vec<_>>().join(", ")
}

fn yaml_scalar(s: &str) -> String {
    let plain = !s.is_empty()
        && s.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.' | '/' | ':'))
        && !s.starts_with(':')
        && !matches!(s, "true" | "false" | "null" | "yes" | "no" | "on" | "off");
    if plain {
        s.to_string()
    } else {
        format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
    }
}

/// `warden/catalog.yaml`: one `tool:` entry per connector tool, then the profile's
/// `catalog.extra.yaml` (resources, A2A skills, `x-memory`, …) appended unchanged.
pub fn generate_catalog(profile: &str, connectors: &[Connector], extra: Option<&str>) -> Result<String, String> {
    let mut out = String::new();
    let _ = writeln!(out, "# yaml-language-server: $schema=https://raw.githubusercontent.com/byQuexo/warden/main/spec/schema/catalog.schema.json");
    let _ = writeln!(out, "# GENERATED by `steward profile generate` from profiles/{profile}/connectors/ and catalog.extra.yaml.");
    let _ = writeln!(out, "# Do not edit; change the connector files instead.");
    let _ = writeln!(out, "version: 1\n\ntool:");
    let mut seen = std::collections::BTreeSet::new();
    for c in connectors {
        let _ = writeln!(out, "  # {} ({})", c.title, c.name);
        for (t, s) in &c.tools {
            let name = format!("{}.{}", c.name, t);
            if !seen.insert(name.clone()) {
                return Err(format!("tool `{name}` is defined twice"));
            }
            let mut fields = vec![format!("scopes: [{}]", list(&s.scopes))];
            if s.sensitivity != "read" {
                fields.push(format!("sensitivity: {}", s.sensitivity));
            }
            if !s.tags.is_empty() {
                fields.push(format!("tags: [{}]", list(&s.tags)));
            }
            let _ = writeln!(out, "  {name}: {{ {} }}", fields.join(", "));
        }
    }
    if let Some(extra) = extra {
        let mut body = String::new();
        for line in extra.lines() {
            let t = line.trim_start();
            if t.starts_with("version:") || t.starts_with("# yaml-language-server") {
                continue;
            }
            if line.starts_with("tool:") {
                return Err("catalog.extra.yaml may not contain a `tool:` section (tools come from connectors)".into());
            }
            body.push_str(line);
            body.push('\n');
        }
        let _ = write!(out, "\n# --- catalog.extra.yaml ---\n{}", body.trim_start_matches('\n'));
    }
    Ok(out)
}

/// Where the generated gateway config points.
pub struct GatewayTargets<'a> {
    /// Base URL of the built-in `steward-mcp` server, e.g. `http://mcp:8100`.
    pub builtin_base: &'a str,
    /// Token endpoint the gateway exchanges user tokens at, e.g. `http://sts:9400/token`.
    pub token_url: &'a str,
    /// Audience of exchanged tokens (what the built-in servers accept).
    pub upstream_audience: &'a str,
}

/// The `upstreams:` block for `warden-gateway`, one entry per connector.
pub fn generate_gateway_yaml(connectors: &[Connector], t: &GatewayTargets) -> String {
    let mut out = String::from("upstreams:\n");
    for c in connectors {
        let _ = writeln!(out, "  {}:", c.name);
        match &c.server {
            ServerSpec::Builtin(b) => {
                let _ = writeln!(out, "    url: {}/{b}/mcp", t.builtin_base.trim_end_matches('/'));
            }
            ServerSpec::Url(u) => {
                let _ = writeln!(out, "    url: {u}");
            }
            ServerSpec::Command(cmd) => {
                let _ = writeln!(out, "    command: [{}]", list(cmd));
                if !c.pass_env.is_empty() {
                    let _ = writeln!(out, "    pass_env: [{}]", list(&c.pass_env));
                }
            }
        }
        if !c.resources.is_empty() {
            let _ = writeln!(out, "    resources: [{}]", list(&c.resources));
        }
        if !matches!(c.server, ServerSpec::Command(_)) {
            let _ = writeln!(
                out,
                "    auth: {{ strategy: token-exchange, token_url: {}, client_id: gateway, secret_env: GATEWAY_STS_SECRET, audience: {} }}",
                t.token_url, t.upstream_audience
            );
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn crm() -> Connector {
        serde_norway::from_str(
            "name: crm\ntitle: CRM\nserver: { builtin: crm }\ntools:\n  list_deals: { scopes: [crm:read] }\n  update_deal: { scopes: [crm:write], sensitivity: write, tags: [money] }\n",
        )
        .unwrap()
    }

    #[test]
    fn catalog_is_valid_warden_yaml() {
        let extra = "version: 1\nx-memory:\n  memory.read_own: { scopes: [memory:own] }\n";
        let y = generate_catalog("acme", &[crm()], Some(extra)).unwrap();
        let cat = warden_core::Catalog::from_yaml_str(&y).unwrap();
        let kinds: Vec<String> = cat.kinds.keys().map(|k| k.as_str().to_string()).collect();
        assert!(kinds.contains(&"tool".to_string()) && kinds.contains(&"x-memory".to_string()), "{kinds:?}");
        assert!(y.contains("crm.update_deal: { scopes: [crm:write], sensitivity: write, tags: [money] }"), "{y}");
    }

    #[test]
    fn duplicate_and_bad_names_are_rejected() {
        assert!(generate_catalog("x", &[crm(), crm()], None).is_err());
        let mut c = crm();
        c.name = "CRM".into();
        assert!(c.validate().is_err());
        assert!(generate_catalog("x", &[crm()], Some("tool:\n  a.b: { scopes: [x] }\n")).is_err());
    }

    #[test]
    fn gateway_upstreams() {
        let y = generate_gateway_yaml(
            &[crm()],
            &GatewayTargets { builtin_base: "http://mcp:8100", token_url: "http://sts:9400/token", upstream_audience: "steward-mcp" },
        );
        assert!(y.contains("url: http://mcp:8100/crm/mcp"), "{y}");
        assert!(y.contains("strategy: token-exchange"), "{y}");
    }
}
